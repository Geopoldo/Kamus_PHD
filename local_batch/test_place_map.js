const assert=require('node:assert/strict'),core=require('./place-map-core.js');
const entities=[{id:'p',kind:'place',label:'Lake'},{id:'n',kind:'person',label:'Full Name'},{id:'s',kind:'surname',label:'Name'}];
const match=(entity,quality='literal',offsets=[[0,4]])=>({entity,quality,offsets});
const original={version:'original',matches:[match('p'),match('n','literal',[[8,17]]),match('s','literal',[[10,17]])]};
const human={version:'human',matches:[match('n','literal',[[8,17]])]};
const page={document_id:'d',document:'f.pdf',page:1,versions:[original,human]};
let rows=core.build(entities,[page],[{...page,versions:[human]}],new Set(['p']));assert.equal(rows[0].pages.size,0,'Do not link across readings');
rows=core.build(entities,[page],[page],new Set(['p']));assert.equal(rows[0].pages.size,1);assert.equal(rows[0].people.get('n').pages.size,1);
const distant={...page,versions:[{version:'original',matches:[match('p'),match('n','cooccurrence',[[8,17]])]}]};
rows=core.build(entities,[distant],[distant],new Set(['p']));assert.equal(rows[0].people.size,0,'Distant names must not become people');
const overlap={...page,versions:[{version:'original',matches:[match('p'),match('n')]}]};
assert.equal(core.build(entities,[overlap],[overlap],new Set(['p']))[0].people.size,0);
assert.equal(core.location({status:'proposed',label:'Lake',latitude:50,longitude:-80},'Renamed'),null);
assert.equal(core.location({status:'unlocated',label:'Lake',latitude:50,longitude:-80},'Lake'),null);
assert.equal(core.project(-80,50)[0],-80);assert.ok(core.project(-80,51)[1]<core.project(-80,50)[1]);
const uncertain={status:'unconfirmed',label:'Lake',latitude:50,longitude:-80,feature_name:'Lake candidate',note:'Possible lake; not confirmed',source_url:'https://example.org/reference'};
const b={x:-85,y:-65,w:10,h:6},anchor=[-82,-63];
const z=core.zoomAt(b,.5,anchor);
assert.equal((anchor[0]-z.x)/z.w,(anchor[0]-b.x)/b.w,'Cursor longitude remains anchored');
assert.equal((anchor[1]-z.y)/z.h,(anchor[1]-b.y)/b.h,'Cursor latitude remains anchored');
assert.deepEqual(core.zoomAt(z,2,anchor),b);
assert.equal(core.zoomAt(b,1e9).w,360);assert.equal(core.zoomAt(b,1e-9).w,.04);
const pinched=core.gesture(b,anchor,anchor,[-81,-62],.5);
assert.equal(pinched.x,z.x-.5);assert.equal(pinched.y,z.y-.5);
const originalPoint=[-79.5,51.3],roundTrip=core.unproject(...core.project(...originalPoint));
assert.ok(Math.abs(roundTrip[1]-originalPoint[1])<1e-9);
assert.equal(core.location(uncertain,'Lake'),uncertain);
assert.ok(core.visible(uncertain,'unconfirmed'));assert.ok(core.visible(uncertain,'located'));
assert.ok(!core.visible(uncertain,'confirmed'));assert.ok(!core.visible(null,'unconfirmed'));
assert.ok(core.visible(null,'unlocated'));
assert.equal(core.location({...uncertain,latitude:95},'Lake'),null);
assert.equal(core.location({...uncertain,needs_recheck:true},'Lake'),null);
const exportRow=core.build(entities,[page],[page],new Set(['p']))[0];
const feature=core.feature(exportRow,uncertain);
assert.deepEqual(feature.geometry.coordinates,[-80,50]);
assert.equal(feature.properties.status,'unconfirmed');assert.equal(feature.properties.note,uncertain.note);
assert.equal(feature.properties.references.length,1);
assert.equal(core.feature(exportRow,{...uncertain,label:'Another lake'}).geometry,null);
console.log('Map: page deduplication, same-reading co-mentions, distant names, overlap and renamed-place checks passed');

const sources=require('./priority-balance-core.js');
const north={...page,folder:'Archive',document:'Archive/North/a.pdf'},south={...page,document_id:'south',folder:'Archive',document:'Archive/South/b.pdf'},similar={...page,document_id:'outside',folder:'Archive2',document:'Archive2/c.pdf'};
assert.deepEqual(sources.sourceFacets([north,south,similar],['Archive/North']).documents,['Archive/North/a.pdf']);
assert.deepEqual(sources.sourceFacets([north,south,similar]).folders,['Archive','Archive/North','Archive/South','Archive2']);
assert.equal(sources.filterEvidence([north,south,similar],{folder:['Archive']}).length,2);
const chosen=sources.filterEvidence([north,south],{folder:['Archive'],document:['Archive/South/b.pdf'],version:['original']});
assert.equal(chosen.length,1);assert.equal(chosen[0].document_id,'south');
const filteredRows=core.build(entities,[north,south,similar],chosen,new Set(['p']));
assert.equal(filteredRows[0].pages.size,1);
assert.equal(core.feature(filteredRows[0],uncertain).properties.references[0].document,'Archive/South/b.pdf');
const emptyRow={entity:{id:'empty',label:'Other lake'},pages:new Map(),people:new Map()};
assert.equal(core.filterRows([...filteredRows,emptyRow]).length,1);
assert.equal(core.filterRows([...filteredRows,emptyRow],{includeEmpty:true}).length,2);
assert.equal(core.filterRows(filteredRows,{category:'unconfirmed'},new Map([['p',uncertain]])).length,1);
assert.equal(core.filterRows(filteredRows,{query:'absent'}).length,0);
console.log('Map source filters: recursive folders, documents, readings, zero mentions and export scope passed');
